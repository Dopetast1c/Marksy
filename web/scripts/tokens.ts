// docs/tokens.json to CSS (docs/design.md 12): the variables of docs/mockups.html (--bg, --accent, --band-good-fg, ...)
// for the light theme, the dark theme by preference and by data-theme, and a Tailwind `@theme inline` block that maps
// utilities (bg-surface, text-ink, text-band-good-fg, rounded-lg, shadow-card, text-h1) onto those variables, so a
// theme or palette switch changes variables only. The variables are unlayered; where a Tailwind key has the same name
// as one of them (--font-body, --shadow-card), Tailwind's own `theme` layer copy loses to it, which is what we want.

type Leaf = string | number | null;
interface Tokens {
  color: { light: ColorSet; dark: ColorSet; subject: Record<string, unknown> };
  font: { display: string; body: string };
  typeScale: Record<string, Record<string, Leaf>>;
  radius: Record<string, string>;
  space: Record<string, string>;
  shadow: { card: string; cardDark?: string };
  tap: { min: string };
  avatar: Record<string, Record<string, string> | string>;
}
interface ColorSet {
  [k: string]: string | Record<string, string | Record<string, string>>;
}

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** Every colour of one theme as [variable name, value], in file order: bg, accent-ink, band-top-fg-text, holiday-fill */
export function colorVars(set: ColorSet): [string, string][] {
  const out: [string, string][] = [];
  const walk = (o: Record<string, unknown>, prefix: string) => {
    for (const [k, v] of Object.entries(o)) {
      const name = prefix ? `${prefix}-${kebab(k)}` : kebab(k);
      if (typeof v === 'string') out.push([name, v]);
      else if (v && typeof v === 'object') walk(v as Record<string, unknown>, name);
    }
  };
  walk(set, '');
  return out;
}

const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}`;

export function tokensToCss(t: Tokens): string {
  const light = colorVars(t.color.light);
  const dark = colorVars(t.color.dark);
  const subjectText = t.color.subject.textLightness as { light: string; dark: string };
  const common = [
    `--font-display: ${t.font.display};`,
    `--font-body: ${t.font.body};`,
    ...Object.entries(t.radius).map(([k, v]) => `--r-${k}: ${v};`),
    `--tap-min: ${t.tap.min};`,
    ...Object.entries(t.avatar)
      .filter(([group]) => !group.startsWith('$'))
      .flatMap(([group, values]) =>
        Object.entries(values as Record<string, string>).map(([k, v]) => `--av-${group}-${k}: ${v};`),
      ),
  ];
  const lightLines = [
    'color-scheme: light;',
    ...light.map(([k, v]) => `--${k}: ${v};`),
    `--shadow-card: ${t.shadow.card};`,
    `--subj-text-l: ${subjectText.light};`,
  ];
  const darkLines = [
    'color-scheme: dark;',
    ...dark.map(([k, v]) => `--${k}: ${v};`),
    `--shadow-card: ${t.shadow.cardDark ?? t.shadow.card};`,
    `--subj-text-l: ${subjectText.dark};`,
  ];
  const theme = [
    '--color-*: initial;',
    ...light.map(([k]) => `--color-${k}: var(--${k});`),
    '--font-*: initial;',
    '--font-display: var(--font-display);',
    '--font-body: var(--font-body);',
    '--radius-*: initial;',
    ...Object.keys(t.radius).map((k) => `--radius-${k}: var(--r-${k});`),
    '--shadow-*: initial;',
    '--shadow-card: var(--shadow-card);',
    // the space scale is n × 4 px (space.1); Tailwind's p-3, gap-4 multiply --spacing
    `--spacing: ${t.space['1']};`,
    '--text-*: initial;',
    ...Object.entries(t.typeScale).flatMap(([k, v]) => [
      `--text-${k}: ${v.size};`,
      `--text-${k}--line-height: ${v.lineHeight};`,
      ...(v.weight != null ? [`--text-${k}--font-weight: ${v.weight};`] : []),
      ...(v.letterSpacing != null ? [`--text-${k}--letter-spacing: ${v.letterSpacing};`] : []),
    ]),
  ];
  // the subject palette's fill (6.6): the hue comes from --sh on the element, grey sets --ss to 0%
  const fill = String(t.color.subject.fill).replace(
    /^hsl\(h (\S+) (\S+)\)$/,
    (_, s: string, l: string) => `hsl(var(--sh, 210) var(--ss, ${s}) ${l})`,
  );
  const subjectUtility = `@utility bg-subject {\n  background-color: ${fill};\n}`;
  return [
    '/* Generated by web/scripts/tokens-to-css.ts from docs/tokens.json. Do not edit: change the tokens and run\n   pnpm --filter @marksy/web tokens. */',
    block(':root', [...common, ...lightLines]),
    [
      '@media (prefers-color-scheme: dark) {',
      '  :root:not([data-theme="light"]) {',
      ...darkLines.map((l) => `    ${l}`),
      '  }',
      '}',
    ].join('\n'),
    block(':root[data-theme="dark"]', darkLines),
    block('@theme inline', theme),
    subjectUtility,
    '',
  ].join('\n\n');
}

/** Hues of the subject palette (6.6); null is grey */
export function subjectHues(t: Tokens): Record<string, number | null> {
  return Object.fromEntries(
    Object.entries(t.color.subject).filter(([k, v]) => !k.startsWith('$') && (typeof v === 'number' || v === null)),
  ) as Record<string, number | null>;
}
