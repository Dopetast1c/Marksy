import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

// `pnpm --filter @marksy/web api:types`: web/src/api/openapi.json (written by the server, src/openapi-export.ts) to
// web/src/api/schema.d.ts, the types of the typed client (docs/design.md 13). A test fails when the types are older
// than the document.

export const OPENAPI_JSON = fileURLToPath(new URL('../src/api/openapi.json', import.meta.url));
export const SCHEMA_TS = fileURLToPath(new URL('../src/api/schema.d.ts', import.meta.url));

export async function schemaTypes(): Promise<string> {
  const ast = await openapiTS(JSON.parse(readFileSync(OPENAPI_JSON, 'utf8')));
  return `// Generated by web/scripts/api-types.ts from src/api/openapi.json. Do not edit.\n\n${astToString(ast)}`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(SCHEMA_TS, await schemaTypes());
  console.log('web/src/api/schema.d.ts written');
}
